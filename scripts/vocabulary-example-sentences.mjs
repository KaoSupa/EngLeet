function escapeRegExp(value) {
  return value.replace(/[.*+?^${}()|[\]\\]/g, "\\$&");
}

function sentenceCase(value) {
  const trimmed = value.trim();
  return trimmed ? trimmed[0].toUpperCase() + trimmed.slice(1) : trimmed;
}

function finishSentence(value) {
  return /[.!?]$/.test(value) ? value : `${value}.`;
}

function normalizeWord(value) {
  return value.trim().toLowerCase().replace(/\s+/g, " ");
}

function containsTargetWord(example, word) {
  const suffixPattern = word.endsWith("e") ? "(?:s|d|ing)?" : "(?:s|ed|ing)?";
  return new RegExp(`\\b${escapeRegExp(word)}${suffixPattern}\\b`, "i").test(
    example,
  );
}

function cleanWordNetExample(example, word) {
  if (!example || !containsTargetWord(example, word)) {
    return null;
  }

  const normalized = example
    .replace(/\s*--\s*/g, "; ")
    .replace(/\s+/g, " ")
    .trim();
  const lower = normalized.toLowerCase();

  if (
    normalized.length < 12 ||
    normalized.length > 120 ||
    UNSAFE_EXAMPLE_PARTS.some((part) => lower.includes(part))
  ) {
    return null;
  }

  return finishSentence(sentenceCase(normalized));
}

function contextualVerbExample(word, definition) {
  const override = VERB_EXAMPLE_OVERRIDES.get(word);
  if (override) {
    return override;
  }

  const normalizedDefinition = definition.toLowerCase();
  const pattern = VERB_DEFINITION_PATTERNS.find(([matcher]) =>
    matcher.test(normalizedDefinition),
  );

  if (pattern) {
    return pattern[1](word);
  }

  return `Try to ${word} with a clear purpose in this situation.`;
}

export function isVerbTemplateExample(value) {
  return VERB_TEMPLATE_PATTERN.test(value ?? "");
}

export function exampleSentenceForVocabularyEntry(entry) {
  const word = normalizeWord(entry.word ?? entry.normalized_word ?? "");
  const partOfSpeech = entry.part_of_speech ?? entry.partOfSpeech ?? null;
  const definition = entry.definition ?? "";

  if (!word || partOfSpeech !== "verb") {
    return entry.example_sentence ?? null;
  }

  if (VERB_EXAMPLE_OVERRIDES.has(word)) {
    return contextualVerbExample(word, definition);
  }

  return (
    cleanWordNetExample(entry.wordnetExample, word) ??
    contextualVerbExample(word, definition)
  );
}
